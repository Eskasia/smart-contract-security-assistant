export type TranslationKey = keyof typeof translations.en;

export function translate(
  locale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
) {
  let text = translations[locale][key];
  for (const [name, value] of Object.entries(values)) {
    text = text.replace(`{${name}}`, String(value)) as typeof text;
  }
  return text;
}

export function useTranslation() {
  const locale = useSettingsStore((state) => state.settings.locale);
  const updateSettings = useSettingsStore((state) => state.updateSettings);
  return {
    locale,
    t: (key: TranslationKey, values?: Record<string, string | number>) =>
      translate(locale, key, values),
    setLocale: (nextLocale: Locale) => updateSettings({ locale: nextLocale }),
    toggleLocale: () => updateSettings({ locale: locale === "zh" ? "en" : "zh" }),
  };
}
